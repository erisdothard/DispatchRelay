/** City centroid, falling back to the state centroid; null when neither is known. */
export function lookupCity(city: string, state: string): LatLng | null {
  const stateCode = state.trim().toUpperCase();
  const cityKey = `${city.trim().toLowerCase()},${stateCode.toLowerCase()}`;
  return CITIES[cityKey] ?? STATES[stateCode] ?? null;
}

const EARTH_RADIUS_MI = 3958.8;

/** Great-circle distance in miles. */
export function distanceMiles([lat1, lng1]: LatLng, [lat2, lng2]: LatLng): number {
  const toRad = (deg: number) => (deg * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_RADIUS_MI * Math.asin(Math.sqrt(a));
}
